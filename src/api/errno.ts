/** 这些码说明凭据不可用，应该引导重新授权，重试没用 */
const NEEDS_REAUTH = new Set([-6, 20016, 20017, 31045]);

/**
 * 常用错误码常量，命名与 Go SDK 的 `api.Errno*` 一一对应：
 *
 *   Go: api.ErrnoAccessTokenExpired  →  JS: api.Errno.AccessTokenExpired
 *
 * 只收录语义明确、且在平台「公共错误码」表与 Go SDK 里含义一致的码。
 * 平台文档明确写了「一个错误码数字未必对应一个接口」，含义有歧义的码
 * （比如 31023、31190）不在这里定义，用 `errnoMessage(errno)` 取通用文案。
 */
export const Errno = {
  Success: 0,
  AccessDenied: -6,
  FileNameIllegal: -7,
  FileAlreadyExist: -8,
  PathNotExist: -9,
  SpaceFull: -10,
  ParamError: 2,
  AsyncTaskRunning: 111,
  AccessTokenExpired: 20016,
  AccessTokenInvalid: 20017,
  LimitExceeded: 31034,
  AccessTokenVerifyFailed: 31045
} as const;

export type ErrnoValue = (typeof Errno)[keyof typeof Errno];

/** 取 errno 的中文说明。没收录的码返回带原始码的兜底文案，不要返回空串。 */
export function errnoMessage(errno: number): string {
  return ERRNO_MESSAGES[errno] ?? '接口返回错误码 ' + errno;
}

/** 这个码是不是已收录。用于判断「要不要把接口原文也展示出来」 */
export function hasErrnoMessage(errno: number): boolean {
  return errno in ERRNO_MESSAGES;
}

/**
 * 需要重新授权吗。这类错误重试多少次都一样，必须让用户重新走一遍授权。
 * 简化模式没有 refresh_token，所以只能重新授权，不能静默续期。
 */
export function needsReauth(errno: number): boolean {
  return NEEDS_REAUTH.has(errno);
}
